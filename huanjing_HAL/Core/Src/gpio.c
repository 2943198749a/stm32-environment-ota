/*
 * ESP32-C3 的 EN 引脚由应用代码控制。
 * 函数单独放在 USER CODE 区，CubeMX 重新生成 gpio.c 时不会覆盖它。
 * 调用前 MX_GPIO_Init 已打开 GPIOE 时钟；将 PE4 拉高后 ESP32 才退出硬件复位。
 */
void Board_Esp32Enable_Init(void)
{
  GPIO_InitTypeDef gpio = {0};

  /* 明确重新配置 PE4，避免它仍处于上电默认的浮空输入状态。 */
  gpio.Pin = GPIO_PIN_4;
  gpio.Mode = GPIO_MODE_OUTPUT_PP;
  gpio.Pull = GPIO_NOPULL;
  gpio.Speed = GPIO_SPEED_FREQ_HIGH;
  HAL_GPIO_Init(GPIOE, &gpio);

  /* EN 拉高：ESP32-C3 退出复位，可以运行 Arduino 网关程序。 */
  HAL_GPIO_WritePin(GPIOE, GPIO_PIN_4, GPIO_PIN_SET);
}

